def canvas():
    return Image.new('RGBA', (16, 16), (0, 0, 0, 0))


def put(img, x, y, c):
    img.putpixel((x % 16, y % 16), rgb(c) + (255,))


def smooth_noise(rnd, scale):
    """A tiling 16x16 field in 0..1: random values on a coarse grid, blended (so shades come in clusters)."""
    n = 16 // scale
    grid = [[rnd.random() for _ in range(n)] for _ in range(n)]
    out = [[0.0] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            gx, gy = x / scale, y / scale
            x0, y0 = int(gx) % n, int(gy) % n
            x1, y1 = (x0 + 1) % n, (y0 + 1) % n
            fx, fy = gx - int(gx), gy - int(gy)
            fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
            a = grid[y0][x0] * (1 - fx) + grid[y0][x1] * fx
            b = grid[y1][x0] * (1 - fx) + grid[y1][x1] * fx
            out[y][x] = a * (1 - fy) + b * fy
    return out


def shade(ramp, v):
    return ramp[max(0, min(len(ramp) - 1, int(v * len(ramp))))]


def cap(name, f, rnd):
    img = canvas()
    field = smooth_noise(rnd, 4)
    fine = smooth_noise(rnd, 2)
    ramp = f['cap']
    mid = ramp[2:4]
    for y in range(16):
        for x in range(16):
            # two close shades in soft clusters, as vanilla's cap: calm from a distance
            v = 0.65 * field[y][x] + 0.2 * fine[y][x] + 0.2 * (rnd.random() - 0.5)
            c = shade(mid, v)
            if rnd.random() < 0.04:
                c = ramp[1]
            put(img, x, y, c)
    s = f['spot']
    if name == 'inkcap':
        # a shaggy cap: torn scales, each a dark curl with a pale lip above it, scattered in loose rows
        for row in range(5):
            y = 1 + row * 3 + rnd.randrange(2)
            x = rnd.randrange(4)
            while x < 16:
                w = 1 + rnd.randrange(2)
                for dx in range(w):
                    put(img, x + dx, y - 1, ramp[-1])
                    put(img, x + dx, y, ramp[1] if dx == 0 else ramp[0])
                if rnd.random() < 0.4:
                    put(img, x, y + 1, s[2])
                x += w + 3 + rnd.randrange(4)
    else:
        # a few big round spots, shaded from the top left like vanilla's, with a shadow under
        spots = [(2, 3, 3), (11, 7, 2), (6, 12, 2), (12, 0, 2)]
        for sx, sy, size in spots:
            cells = [(dx, dy) for dy in range(size) for dx in range(size)
                     if size < 3 or (dx, dy) not in ((size - 1, size - 1), (0, size - 1))]
            for dx, dy in cells:
                c = s[2] if dx == 0 and dy == 0 else s[1]
                if dx + dy >= size and size > 2:
                    c = s[0]
                put(img, sx + dx, sy + dy, c)
    return img


def inside(f, rnd):
    img = canvas()
    field = smooth_noise(rnd, 4)
    ramp = f['inside']
    for y in range(16):
        for x in range(16):
            # faint diagonal mottling, as vanilla's inside has
            v = 0.9 * field[y][x] + 0.1 * (((x + y) % 5) / 4.0)
            put(img, x, y, shade(ramp, v))
    return img


def stem_side(f, rnd, ramp, fibre):
    img = canvas()
    cols = [rnd.random() for _ in range(16)]
    for x in range(16):
        # each column is a fibre: its own shade, softly varied up its length
        base = 0.25 + 0.6 * cols[x]
        drift = rnd.random() * 6.28
        for y in range(16):
            v = base + 0.12 * ((y * 0.4 + drift) % 1.0 - 0.5)
            if rnd.random() < 0.08:
                v -= 0.25
            put(img, x, y, shade(ramp, v))
    if fibre:
        # (glowcap) two faint glowing threads running up the stem
        for x0 in (4, 11):
            x = x0
            for y in range(16):
                if rnd.random() < 0.25:
                    x += rnd.choice((-1, 1))
                put(img, x, y, fibre)
    return img


def stem_top(f, ramp, rind, fibre):
    img = canvas()
    for y in range(16):
        for x in range(16):
            edge = max(abs(x - 7.5), abs(y - 7.5))
            d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
            if edge > 6.5:
                c = rind[1] if (x * 5 + y * 3) % 4 else rind[0]
            elif d < 1.6:
                c = fibre or ramp[1]
            else:
                # a soft spongy flesh with faint rings toward the core
                c = ramp[2] if int(d * 0.75) % 2 else ramp[3]
                if (x * 7 + y * 11) % 9 == 0:
                    c = ramp[4] if len(ramp) > 4 else ramp[3]
            put(img, x, y, c)
    return img


def planks(f, rnd):
    img = canvas()
    r = f['planks']
    # one joint per board, staggered, as oak's
    joints = [(5,), (12,), (2,), (9,)]
    for board in range(4):
        top = board * 4
        for dy in range(4):
            y = top + dy
            x = 0
            while x < 16:
                # grain in streaks along the board
                run = 2 + rnd.randrange(5)
                if dy == 3:
                    c = r[0]
                elif dy == 0:
                    c = r[3] if rnd.random() < 0.7 else r[2]
                else:
                    c = rnd.choice((r[2], r[2], r[2], r[1], r[3]))
                for i in range(run):
                    put(img, x + i, y, c)
                x += run
        for jx in joints[board]:
            for dy in range(3):
                put(img, jx, top + dy, r[0] if dy else r[1])
    return img


def gills(f, rnd, tip):
    """A curtain of hanging strands (cutout cross model): brightest at the tips, which glow."""
    img = canvas()
    g = f['gill']
    for x in range(16):
        if x % 2 and rnd.random() < 0.65 or not x % 2 and rnd.random() < 0.15:
            continue
        length = 16 if not tip else 5 + rnd.randrange(10)
        for y in range(length):
            c = g[1] if rnd.random() < 0.7 else g[0]
            if tip and y >= length - 3:
                c = g[2]
            if tip and y == length - 1:
                c = g[3]
            put(img, x, y, c)
    return img


def paint_all():
    out = {}
    for name, f in FUNGI.items():
        rnd = random.Random(name)
        out[f'{name}_cap'] = cap(name, f, rnd)
        out[f'{name}_cap_inside'] = inside(f, rnd)
        out[f'{name}_stem'] = stem_side(f, rnd, f['stem'], f['fibre'])
        out[f'{name}_stem_top'] = stem_top(f, f['stem'], f['stem'][:3], f['fibre'])
        out[f'stripped_{name}_stem'] = stem_side(f, rnd, f['stripped'], None)
        out[f'stripped_{name}_stem_top'] = stem_top(f, f['stripped'], f['stripped'][:3], None)
        out[f'{name}_planks'] = planks(f, rnd)
        if 'gill' in f:
            out[f'{name}_gills'] = gills(f, rnd, False)
            out[f'{name}_gills_tip'] = gills(f, rnd, True)
    return out


if __name__ == '__main__':
    folder = sys.argv[1] if len(sys.argv) > 1 else OUT
    os.makedirs(folder, exist_ok=True)
    for name, img in paint_all().items():
        img.save(os.path.join(folder, name + '.png'))
    print('wrote', len(paint_all()), 'textures to', folder)
