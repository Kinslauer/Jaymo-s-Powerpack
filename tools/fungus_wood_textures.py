"""Paints the giant fungi's block textures (glowwood/FungusWood: glowcap, bouncecap, inkcap) in the pack's vanilla style,
replacing the Spore & Stem art (generated by its script, flat and noisy beside vanilla's huge mushrooms).

    python3 -I tools/fungus_wood_textures.py            # writes kingdoms/.../textures/block/<id>.png
    python3 -I tools/fungus_wood_textures.py <folder>   # writes them somewhere else (to preview)

What it paints, for each fungus: the cap (outside, with spots or scales), the cap's inside, the stem's side and top,
the stripped stem's side and top, and the planks; and the glowcap's gill curtains (gills and gills_tip). Shapes follow
vanilla's: the cap like red_mushroom_block (soft clusters of two or three shades, a few shaded spots), the inside like
mushroom_block_inside, the stem like mushroom_stem (fine vertical fibres), the planks in four boards with offset joints
like oak_planks. Every pixel is drawn here from a seeded pattern and a small colour ramp; nothing is copied from vanilla.
Light comes from the top left. Tuning: the ramps in FUNGI.
"""
import os
import random
import sys
from PIL import Image

OUT = os.path.join(os.path.dirname(__file__), '..', 'kingdoms', 'src', 'main', 'resources', 'assets',
                   'jaymoskingdoms', 'textures', 'block')


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


# Each ramp runs dark to light.
