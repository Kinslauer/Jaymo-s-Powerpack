"""Writes docs/codemap/<project>.md: one line per Java class with what it does and its main methods.

Agents read (or grep) the map first and open only the files they need, instead of searching thousands of files.
The Release workflow (tools/release.py) runs this after every merge to master and commits the maps; PRs don't commit
them, since every PR touching them conflicted with the next. Run it locally to see your own new classes, then put
master's maps back before the PR (`git checkout origin/master -- docs/codemap`).
`python3 tools/codemap.py --check` exits 1 if a map is out of date.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECTS = {
    "powers": "src",
    "kingdoms": "kingdoms/src",
    "kitchen": "kitchen/src",
}
OUT = os.path.join(ROOT, "docs", "codemap")
SUMMARY_MAX = 170   # characters of the class comment kept
METHODS_MAX = 10    # method names listed per class

DECL = re.compile(r"^(?:public |protected |private )?(?:static )?(?:abstract |final |sealed |non-sealed )*"
                  r"(class|interface|enum|record|@interface) (\w+)([^{]*)", re.M)
METHOD = re.compile(r"^(?:\t| {4})(?:@\w+(?:\([^)]*\))?\s+)*((?:public|protected|static|final|synchronized|default|abstract)\s+)+"
                    r"(?:<[^>]+>\s+)?[\w<>\[\],.? ]+?\s+(\w+)\s*\(", re.M)
SKIP = {"if", "for", "while", "switch", "return", "new", "catch"}


def summary(text, at):
    head = text[:at]
    m = re.search(r"/\*\*(.*?)\*/\s*(?:@[\w.]+(?:\([^)]*\))?\s*)*$", head, re.S)
    if m:
        body = re.sub(r"^\s*\* ?", "", m.group(1), flags=re.M)
    else:
        lines = []
        for line in reversed(head.rstrip().splitlines()):
            s = line.strip()
            if s.startswith("//"):
                lines.insert(0, s[2:].strip())
            elif s.startswith("@"):
                continue
            else:
                break
        body = " ".join(lines)
    body = re.sub(r"\{@\w+ ([^}]*)\}", r"\1", body)
    body = re.sub(r"<[^>]+>", " ", body)
    body = re.sub(r"\s+", " ", body).strip()
    body = re.sub(r"^\(\d+\.\d+\.\d+\)\s*", "", body)
    end = next((e for e in re.finditer(r"(?<=[a-z0-9)'\"])[.;] ", body) if e.end() > 25), None)
    if end:
        body = body[:end.start() + 1]
    if len(body) > SUMMARY_MAX:
        body = body[:SUMMARY_MAX].rsplit(" ", 1)[0] + "..."
    return body


def entry(path, src_root):
    text = open(path, encoding="utf-8", errors="replace").read()
    d = DECL.search(text)
    if not d:
        return None
    kind, name, rest = d.groups()
    sup = ""
    m = re.search(r"\b(extends|implements)\s+([\w.]+)", rest)
    if m:
        sup = f" : {m.group(2)}"
    methods = []
    for mm in METHOD.finditer(text):
        n = mm.group(2)
        if n[0].islower() and n not in SKIP and n not in methods:
            methods.append(n)
    more = len(methods) - METHODS_MAX
    ms = ", ".join(methods[:METHODS_MAX]) + (f" +{more}" if more > 0 else "")
    lines = text.count("\n") + 1
    rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
    kind = "" if kind == "class" else f" ({kind})"
    out = f"- `{name}`{kind}{sup} [{lines}] `{rel}`: {summary(text, d.start())}"
    if ms:
        out += f" Methods: {ms}"
    return out


def build(project, src):
    base = os.path.join(ROOT, src)
    groups = {}
    for side in ("main", "client"):
        java = os.path.join(base, side, "java")
        for dirpath, _, files in os.walk(java):
            for f in sorted(files):
                if f.endswith(".java"):
                    pkg = os.path.relpath(dirpath, java).replace(os.sep, ".")
                    e = entry(os.path.join(dirpath, f), java)
                    if e:
                        groups.setdefault((side, pkg), []).append(e)
    count = sum(len(v) for v in groups.values())
    out = [f"# Code map: {project}", "",
           f"Generated by `tools/codemap.py` ({count} classes). One line per class: name, `[lines]`, path, what it does,"
           " then its main methods. Grep this before searching the code; regenerate after adding classes.", ""]
    for (side, pkg) in sorted(groups):
        out.append(f"## {pkg} ({side})")
        out.extend(sorted(groups[(side, pkg)], key=str.lower))
        out.append("")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    stale = []
    for project, src in PROJECTS.items():
        if not os.path.isdir(os.path.join(ROOT, src)):
            continue
        text = build(project, src)
        path = os.path.join(OUT, project + ".md")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(project)
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if check:
        print("out of date: " + ", ".join(stale) if stale else "code maps are up to date")
        return 1 if stale else 0
    print("written: " + (", ".join(stale) or "nothing changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
