def icon(name, grid, **extra):
    rows = grid.strip('\n').split('\n')
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    ICONS[name] = (rows, {**BASE, **{k.lstrip('_'): v for k, v in extra.items()}})


