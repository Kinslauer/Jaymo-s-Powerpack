VAN = None
def van(n): return Image.open(f'{VAN}/{n}.png').convert('RGBA')
def lum(c): return .299 * c[0] + .587 * c[1] + .114 * c[2]
def H(*cs): return [hx(c) for c in cs]

def recolor(im, colors, ramp):
    """map the given vanilla colours (any order) onto ramp by brightness rank"""
    colors = sorted({hx(c) if isinstance(c, str) else c for c in colors}, key=lum)
    m = {c: ramp[min(len(ramp) - 1, round(i * (len(ramp) - 1) / max(1, len(colors) - 1)))] for i, c in enumerate(colors)}
    px = im.load()
    for y in range(16):
        for x in range(16):
            c = px[x, y]
            if c[3] and c[:3] in m: px[x, y] = m[c[:3]] + (255,)
    return im
def shift(im, fn, only=None):
    px = im.load()
    for y in range(16):
        for x in range(16):
            c = px[x, y]
            if c[3] and (only is None or only(x, y, c)): px[x, y] = tuple(max(0, min(255, int(v))) for v in fn(c[:3])) + (255,)
    return im
def dots(im, pts, col):
    px = im.load(); col = hx(col) if isinstance(col, str) else col
    for x, y in pts: px[x, y] = col + (255,)
    return im
def colors_of(im):
    px = im.load(); return {px[x, y][:3] for y in range(16) for x in range(16) if px[x, y][3]}

