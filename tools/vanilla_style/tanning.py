def main(vanilla):
    os.makedirs(f'{OUT}/item', exist_ok=True)
    os.makedirs(f'{OUT}/block', exist_ok=True)
    for name, (grid, mat, extra) in ICONS.items():
        paint(grid, mat, extra).save(f'{OUT}/item/{name}.png')
    # tanned leather: vanilla's leather, deeper and browner from the bark
    recolour(f'{vanilla}/item/leather.png', ('2a170b', '45260f', '673a1a', '7e4a22', '9b5e2e', 'b0713a')).save(f'{OUT}/item/tanned_leather.png')
    # hemp seeds: vanilla's wheat seeds, grey-brown and speckled
    recolour(f'{vanilla}/item/wheat_seeds.png', ('3b3426', '5a5038', '766a4c', '8f8462', 'a99d7a', 'c2b896')).save(f'{OUT}/item/hemp_seeds.png')
    # the crop: vanilla's wheat stages, in hemp's deep green; the top, its ripe wheat as hemp's leafy head
    green = ('1f4a14', '2c6119', '3a7a20', '4c9128', '62a835', '7cbf48', '96d25e')
    for stage, src in enumerate(('wheat_stage1', 'wheat_stage3', 'wheat_stage5', 'wheat_stage6')):
        recolour(f'{vanilla}/block/{src}.png', green).save(f'{OUT}/block/hemp_stage{stage}.png')
    recolour(f'{vanilla}/block/wheat_stage7.png', ('2a5418', '3a6e20', '4f8a2b', '67a238', '82b84c', '9ccb63')).save(f'{OUT}/block/hemp_top.png')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit('usage: tanning.py <vanilla 26.3 textures folder, holding item/ and block/>')
    main(sys.argv[1])
