"""Jaymo's Kitchen tanning and hemp art (from Better With Mods' ideas, MIT; our own pixels): 16x16 item icons and the
hemp crop's block textures.

Run from the repository root with vanilla 26.3's textures folder (the one holding item/ and block/):
    python3 -I tools/vanilla_style/tanning.py <vanilla textures folder>
Writes into kitchen/src/main/resources/assets/jaymoskitchen/textures (item/, block/).
Where vanilla has the thing, its pixels are reused in new colours (tanned leather is vanilla's leather, hemp seeds its
wheat seeds, the hemp crop its wheat stages); the rest is drawn on a 16x16 grid with vstyle.paint (digits are a
vanilla material ramp, the other letters listed per icon), lit from the top left like vanilla's own items.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vstyle import paint, hx
from PIL import Image

OUT = 'kitchen/src/main/resources/assets/jaymoskitchen/textures'


def recolour(src, ramp):
    """vanilla's pixels, each colour swapped by brightness rank for the same rank of a new ramp (dark to light)."""
    im = Image.open(src).convert('RGBA'); px = im.load()
    cols = sorted({px[x, y][:3] for x in range(16) for y in range(16) if px[x, y][3]}, key=lambda c: (sum(c), c))
    ramp = [hx(c) for c in ramp]
    to = {c: ramp[round(i * (len(ramp) - 1) / max(1, len(cols) - 1))] for i, c in enumerate(cols)}
    out = Image.new('RGBA', (16, 16)); op = out.load()
    for y in range(16):
        for x in range(16):
            if px[x, y][3]:
                op[x, y] = to[px[x, y][:3]] + (255,)
    return out


