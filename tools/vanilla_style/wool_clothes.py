def shade(mask):
    rows = mask.strip('\n').split('\n')
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    filled = {(x, y) for y in range(16) for x in range(16) if rows[y][x] != '.'}
    im = Image.new('RGBA', (16, 16)); px = im.load()
    for (x, y) in filled:
        n = {(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))}
        if not n <= filled:
            lit = (x - 1, y) not in filled or (x, y - 1) not in filled
            dark = (x + 1, y) not in filled or (x, y + 1) not in filled
            g = GREY['B'] if lit and not dark else GREY['A']
        elif rows[y][x] == 'c':
            g = GREY['C'] if x % 2 else GREY['D']
        else:
            g = GREY['D'] if x % 2 else GREY['E']
            # a little shade toward the lower right, like vanilla's armour
            if (x + 1, y + 1) not in filled or (x + 2, y) not in filled:
                g -= 18
        px[x, y] = (g, g, g, 255)
    return im


def knit_layer(src):
    """vanilla leather's worn layer, lightened, with knit ribs down every face."""
    im = Image.open(src).convert('RGBA'); px = im.load()
    out = Image.new('RGBA', im.size); op = out.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = px[x, y]
            if not a:
                continue
            v = min(255, int((r + g + b) / 3 * 1.06) + (8 if x % 2 == 0 else -10))
            op[x, y] = (v, v, v, 255)
    return out


def main(vanilla):
    os.makedirs(f'{OUT}/item', exist_ok=True)
    for name, mask in ICONS.items():
        shade(mask).save(f'{OUT}/item/{name}.png')
    for layer in ('humanoid', 'humanoid_leggings'):
        d = f'{OUT}/entity/equipment/{layer}'
        os.makedirs(d, exist_ok=True)
        knit_layer(f'{vanilla}/entity/equipment/{layer}/leather.png').save(f'{d}/wool.png')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit('usage: wool_clothes.py <vanilla 26.3 textures folder, holding item/ and entity/>')
    main(sys.argv[1])
