IRON7 = ('191919', '2d2d2d', '6b6b6b', '969696', 'c6c6c6', 'd8d8d8', 'ffffff')
def armour(piece, ramp, marks=None):
    """vanilla iron armour piece in another 7-step ramp; marks(x, y, level) may return a colour to paint instead"""
    im = kitchen.van(f'iron_{piece}'); px = im.load()
    lv = {hx(c): i for i, c in enumerate(IRON7)}
    for y in range(16):
        for x in range(16):
            c = px[x, y]
            if c[3]:
                l = lv[c[:3]]; n = ramp[l]
                if marks:
                    m = marks(x, y, l)
                    if m: n = hx(m) if isinstance(m, str) else m
                px[x, y] = n + (255,)
    return im

