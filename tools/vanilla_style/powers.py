# ---- frost lance: vanilla's iron spear, head in ice, shaft in frosted blue
def recolor(im, table):
    im = im.copy(); px = im.load()
    for y in range(16):
        for x in range(16):
            p = px[x, y]
            if p[3] and p[:3] in table: px[x, y] = table[p[:3]] + (255,)
    return im

def frost_lance(van):
    sp = Image.open(os.path.join(van, 'iron_spear.png')).convert('RGBA')
    t = {hx(a): hx(b) for a, b in {
        '181818': '1a3a66', '444444': '285a96', '6b6b6b': '3c78b4', '545758': '3c78b4', '858585': '5096d2',
        'b1b1b1': '96d2f0', 'd8d8d8': 'c8ecff', 'ffffff': 'e8faff',
        '281e0b': '102848', '493615': '1a3a66', '684e1e': '285a96', '896727': '5096d2',
        '411805': '1a3a66', '67290b': '285a96', 'a34b22': '5096d2', 'ba5f34': '96d2f0'}.items()}
    return recolor(sp, t)

