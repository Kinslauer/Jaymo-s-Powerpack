def hx(s): return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))
def lum(c): return (.299 * c[0] + .587 * c[1] + .114 * c[2]) / 255
def mix(a, b, t=.5): return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

