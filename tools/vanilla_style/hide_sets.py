def set_name(style, shade): return style if shade == 'light' else 'dark_' + style

def grid(s):
    r = s.strip('\n').split('\n')
    assert len(r) == 16 and all(len(x) == 16 for x in r), [len(x) for x in r]
    return r

def icon(style, piece, shade):
    pal = PALETTES[shade]; hide, fur = pal['hide'], pal['fur']
    g = grid(ICONS[style][piece]); hg, fg = GLINTS[style][piece]
    def at(x, y): return g[y][x] if 0 <= x < 16 and 0 <= y < 16 else '.'
    im = Image.new('RGBA', (16, 16)); px = im.load()
    for y in range(16):
        for x in range(16):
            c = g[y][x]
            if c == '.': continue
            n = dict(u=at(x, y - 1), l=at(x - 1, y), d=at(x, y + 1), r=at(x + 1, y))
            edge = '.' in n.values()
            lit = (n['u'] == '.' or n['l'] == '.') and not (n['d'] == '.' or n['r'] == '.')
            mat = c
            if c in 'sbk' and edge:                # an accent on the silhouette takes the outline of what it sits on
                around = [v for v in n.values() if v in 'HF']
                mat = 'F' if around.count('F') > around.count('H') else 'H'
            if mat == 'k': col = HOLLOW
            elif mat == 's': col = SINEW
            elif mat == 'b': col = BONE
            elif edge: col = (hide[2] if lit else hide[0]) if mat == 'H' else (fur[1] if lit else fur[0])
            else:
                same = lambda q: q != '.' and q != 'k' and (q == c or q in 'sb')
                a = 0
                while same(at(x - a - 1, y - a - 1)): a += 1
                b = 0
                while same(at(x + b + 1, y + b + 1)): b += 1
                if c == 'H':
                    lv = 5 if a == 0 else 2 if b == 0 else 4 if a / (a + b) < .45 else 3
                    if n['u'] in 'Fk' and lv > 3: lv = 3      # shadow under the fur and inside the hood
                    if (x, y) in hg: lv = 6
                    col = hide[lv]
                else:
                    lv = 3 if a == 0 else 2 if b == 0 else 3 if a / (a + b) < .5 else 2
                    if lv == 3 and (x + 2 * y) % 4 == 0: lv = 2   # a strand of hair, never a checker
                    if (x, y) in fg: lv = 4
                    col = fur[lv]
            px[x, y] = col + (255,)
    check_icon(im, shade, f'{style} {piece} {shade}')
    return im

SLOT = hx('8b8b8b')
def check_icon(im, shade, label):
    """the judges' faults, as checks: outline shades on the silhouette, nothing near the slot's grey on it, no
    one-pixel checker, and bone, fur and sinew far enough apart in value"""
    pal = PALETTES[shade]; px = im.load()
    outline = {pal['hide'][0], pal['hide'][2], pal['fur'][0], pal['fur'][1]}
    op = lambda x, y: 0 <= x < 16 and 0 <= y < 16 and px[x, y][3] > 0
    for y in range(16):
        for x in range(16):
            if not op(x, y): continue
            c = px[x, y][:3]
            if not all(op(x + dx, y + dy) for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0))):
                assert c in outline, (label, 'silhouette pixel not an outline shade', x, y, c)
                assert sum(abs(c[i] - SLOT[i]) for i in range(3)) > 60, (label, 'silhouette near slot grey', x, y)
                assert max(c) >= 40, (label, 'black outline', x, y)
            if x < 14 and y < 14 and all(op(x + i, y + j) for i in range(3) for j in range(3)):
                a, b = px[x, y][:3], px[x + 1, y][:3]       # a 3x3 patch of two colours alternating is a dither
                assert a == b or not all(px[x + i, y + j][:3] == (a if (i + j) % 2 == 0 else b)
                                         for i in range(3) for j in range(3)), (label, 'checker', x, y)
    f = pal['fur']
    assert lum(BONE) - lum(f[4]) >= .08, (label, 'bone and fur glint too close')
    assert abs(lum(f[3]) - lum(SINEW)) >= .08, (label, 'sinew and fur too close')

# ---- worn layers: boxes on the 64x32 humanoid sheet (u, v, width, height, depth) ----
BOX = {'head': (0, 0, 8, 8, 8), 'body': (16, 16, 8, 12, 4), 'arm': (40, 16, 4, 12, 4), 'leg': (0, 16, 4, 12, 4)}
SIDES = ('right', 'front', 'left', 'back')

def face(part, f):
    u, v, w, h, d = BOX[part]
    return dict(top=(u + d, v, w, d), bottom=(u + d + w, v, w, d), right=(u, v + d, d, h), front=(u + d, v + d, w, h),
                left=(u + d + w, v + d, d, h), back=(u + 2 * d + w, v + d, w, h))[f]

class Sheet:
    """material letters on a 64x32 worn layer"""
    def __init__(self): self.m = {}
    def put(self, part, f, x, y, ch):
        fx, fy, w, h = face(part, f)
        if 0 <= x < w and 0 <= y < h: self.m[fx + x, fy + y] = ch
    def fill(self, part, f, ch, rows=None, cols=None, only=None):
        fx, fy, w, h = face(part, f)
        for y in rows if rows is not None else range(h):
            for x in cols if cols is not None else range(w):
                if 0 <= x < w and 0 <= y < h and (only is None or (fx + x, fy + y) in only):
                    self.m[fx + x, fy + y] = ch
    def ring(self, part, ch, rows, faces=SIDES, only=None):
        for f in faces: self.fill(part, f, ch, rows=rows, only=only)
    def ragged(self, part, row, faces=SIDES):
        """every other pixel of a row torn away"""
        for f in faces:
            fx, fy, w, h = face(part, f)
            for x in range(w):
                if (fx + x) % 2: self.m.pop((fx + x, fy + row), None)

def region(part, f, alpha):
    fx, fy, w, h = face(part, f)
    return {(x, y) for y in range(fy, fy + h) for x in range(fx, fx + w) if alpha(x, y)}

def column_rows(cov, xs, ys):
    """per column, the covered rows top to bottom"""
    return {x: [y for y in ys if (x, y) in cov] for x in xs}

def design(style, layer, van_alpha):
    """the material sheet for one set's layer"""
    s = Sheet()
    if style == 'trapper':                         # vanilla's own leather cut
        cov = {(x, y) for y in range(32) for x in range(64) if van_alpha(x, y)}
        for p in cov: s.m[p] = 'H'
        if layer == 'humanoid':
            for x, ys in column_rows(cov, range(32), range(8, 16)).items():
                for y in ys[-2:]: s.m[x, y] = 'F'                     # fur brow round the hood's rim
            s.fill('body', 'front', 'F', rows=[0]); s.ring('body', 'F', [0], faces=('right', 'left', 'back'), only=cov)
            s.fill('arm', 'top', 'F'); s.ring('arm', 'F', [0, 1], only=cov)   # fur mantle on the shoulders
            for r in range(2, 9): s.put('body', 'front', 3 + r % 2, r, 's')    # laced front
            s.put('body', 'front', 3, 1, 'b'); s.put('body', 'front', 4, 1, 'b')
            s.ring('leg', 'F', [6, 7], only=cov)                       # boot cuffs
            for r in (8, 9, 10): s.put('leg', 'front', 1 + r % 2, r, 's')
        else:
            s.ring('body', 'F', [7], only=cov)                         # fur waistband, bone toggle
            s.put('body', 'front', 3, 7, 'b'); s.put('body', 'front', 4, 7, 'b')
            s.put('leg', 'front', 1, 4, 's'); s.put('leg', 'front', 2, 4, 's')
        return s
    if style == 'caveman':                         # the old scraps cut: hood rim, one-shoulder pelt, loincloth, wraps
        mk = Image.open(os.path.join(HERE, 'masks', f'caveman_{layer}.png')).convert('L').load()
        cov = {(x, y) for y in range(32) for x in range(64) if mk[x, y]}
        for p in cov: s.m[p] = 'H'
        if layer == 'humanoid':
            for x in range(32):
                if (x, 10) in cov: s.m[x, 10] = 'F'                   # fur brow
            body = region('body', 'front', lambda x, y: (x, y) in cov) | region('body', 'right', lambda x, y: (x, y) in cov) \
                | region('body', 'left', lambda x, y: (x, y) in cov) | region('body', 'back', lambda x, y: (x, y) in cov) \
                | region('body', 'top', lambda x, y: (x, y) in cov)
            for x, ys in column_rows(body, range(16, 40), range(16, 32)).items():
                top = [y for y in ys if y < 28]
                for y in top[:2]: s.m[x, y] = 'F'                     # the pelt's fur edge over the shoulder
                if len(top) > 4 and x % 3 == 0: s.m[x, top[3]] = 's'  # sinew stitching under it
            if (21, 21) in cov: s.m[21, 21] = 'b'                     # the bone pin at the shoulder knot
            for x in range(16):
                if (x, 28) in cov: s.m[x, 28] = 'F'                   # boot cuffs
            for x, y in ((5, 29), (6, 30), (1, 29), (2, 30), (9, 29), (10, 30), (13, 29), (14, 30)):
                if (x, y) in cov: s.m[x, y] = 's'                     # foot wraps
        else:
            for x in range(16, 40):
                if (x, 27) in cov: s.m[x, 27] = 'F'                   # fur belt
            for x, ch in ((22, 's'), (23, 'b'), (24, 'b'), (25, 's')):
                if (x, 28) in cov: s.m[x, 28] = ch
            for x in range(16):
                if (x, 23) in cov and x % 4 in (1, 2): s.m[x, 23] = 's'
        return s
    # barbarian: wolf pelt over the head and down the back, fur mantle, bare arms, fur loincloth, fur-cuffed wraps
    if layer == 'humanoid':
        s.fill('head', 'top', 'H')
        for x, y in ((0, 6), (1, 6), (0, 7), (6, 6), (7, 6), (7, 7)): s.put('head', 'top', x, y, 'F')   # ears
        s.ring('head', 'H', [0, 1]); s.ring('head', 'F', [2, 3])
        for x in (0, 1, 6, 7): s.put('head', 'front', x, 0, 'F')      # the ears seen from the front
        s.fill('head', 'right', 'H', rows=range(4, 8)); s.fill('head', 'left', 'H', rows=range(4, 8))
        s.fill('head', 'back', 'F', rows=range(4, 8))
        s.ragged('head', 7, faces=('right', 'left'))
        s.put('head', 'front', 2, 3, 'b'); s.put('head', 'front', 5, 3, 'b')     # fangs in the brow, clear of the eyes
        s.fill('body', 'top', 'F'); s.ring('body', 'F', [0, 1, 2]); s.ring('body', 'H', range(3, 12))
        s.ragged('body', 11)
        s.put('body', 'front', 1, 3, 's'); s.put('body', 'front', 6, 3, 's')     # tooth necklace
        s.put('body', 'front', 2, 4, 'b'); s.put('body', 'front', 5, 4, 'b')
        s.put('body', 'front', 3, 5, 'b'); s.put('body', 'front', 4, 5, 'b')
        s.fill('arm', 'top', 'F'); s.ring('arm', 'F', [0, 1, 2]); s.ragged('arm', 2)
        s.ring('leg', 'F', [6, 7]); s.ring('leg', 'H', range(8, 12)); s.fill('leg', 'bottom', 'H')
        for r in (8, 9, 10): s.put('leg', 'front', 1 + r % 2, r, 's')
    else:
        s.ring('body', 'H', [7]); s.ring('body', 'F', range(8, 12)); s.ragged('body', 11, faces=('right', 'left'))
        s.put('body', 'front', 1, 7, 's'); s.put('body', 'front', 3, 7, 'b'); s.put('body', 'front', 5, 7, 's')
        s.fill('leg', 'top', 'F'); s.ring('leg', 'F', range(0, 4)); s.ring('leg', 'H', range(4, 7))
        s.put('leg', 'front', 1, 5, 's'); s.put('leg', 'front', 2, 5, 's')
    return s

def by_rank_levels(im):
    """vanilla's shading: each opaque pixel's brightness rank among the image's colours, 0..1"""
    px = im.load(); w, h = im.size
    cols = sorted({px[x, y][:3] for y in range(h) for x in range(w) if px[x, y][3]}, key=lum)
    lv = {c: i / max(1, len(cols) - 1) for i, c in enumerate(cols)}
    return {(x, y): lv[px[x, y][:3]] for y in range(h) for x in range(w) if px[x, y][3]}

def worn_ramp(r): return [r[3], mix(r[3], r[4]), r[4], mix(r[4], r[5]), r[5], mix(r[5], r[6]), r[6]]
def fur_worn(f): return [f[1], mix(f[1], f[2]), f[2], mix(f[2], f[3]), f[3], mix(f[3], f[4]), f[4]]

def worn(style, layer, shade, van):
    """van: vanilla's leather worn layer for this layer"""
    pal = PALETTES[shade]; hr, fr = worn_ramp(pal['hide']), fur_worn(pal['fur'])
    vp = van.load(); lev = by_rank_levels(van)
    s = design(style, layer, lambda x, y: vp[x, y][3] > 0)
    im = Image.new('RGBA', (64, 32)); px = im.load()
    for (x, y), c in s.m.items():
        lv = round(lev.get((x, y), .45) * 6)
        if c == 'H':
            if s.m.get((x, y - 1)) == 'F': lv = max(0, lv - 2)        # shadow under the fur
            col = hr[lv]
        elif c == 'F': col = fr[lv]
        elif c == 's': col = SINEW
        elif c == 'b': col = BONE
        else: col = HOLLOW
        px[x, y] = col + (255,)
    return im

def build(van_root):
    """{'item/armory/<set>_<piece>': image}, {'<layer>/<set>': image}"""
    items, layers = {}, {}
    for style, shade in SETS:
        n = set_name(style, shade)
        for p in PIECES: items[f'armory/{n}_{p}'] = icon(style, p, shade)
        for layer in ('humanoid', 'humanoid_leggings'):
            van = Image.open(f'{van_root}/entity/equipment/{layer}/leather.png').convert('RGBA')
            layers[f'{layer}/{n}'] = worn(style, layer, shade, van)
    return items, layers
