"""The three primitive hide sets and their dark makes (Andy, 2026-11-24: "i want all 3, and they can have a darker
variation made from darker hides"). Called by armour.py, which writes them into the vanilla_style pack; they are our
own art, so the same images are the mod's base textures too.

  caveman   one-shoulder pelt, hood with a dark face opening, loincloth with tails, wrapped boots (the cave band)
  trapper   vanilla's slot shapes in stitched hide: fur brow, fur mantle, laced front, bone toggles
  barbarian eared wolf-pelt hood with fangs, fur mantle and tooth necklace, fur loincloth, fur-cuffed wraps
  dark_*    the same, in darker hide and fur (bear fur, hardened leather, or a hide smoked over charcoal)

Icons are letter grids (H hide, F fur, s sinew, b bone, k inside of the hood, '.' clear), shaded here from the
top-left like vanilla. Worn layers paint the same materials onto vanilla's leather UVs (caveman keeps its old scraps
cut, masks/caveman_*.png) and take vanilla leather's shading by brightness rank."""
