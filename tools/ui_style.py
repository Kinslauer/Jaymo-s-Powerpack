#!/usr/bin/env python3
"""The shared screen style, written into each mod from one source.

Powers, Kingdoms and Kitchen can't depend on each other, so each keeps its own copy of the screen style
(UiStyle, Ui, KitchenUi) and of the flat button widget (FlatButton). The copies drifted apart once; now they are
generated from tools/ui_style/core.java.txt and tools/ui_style/FlatButton.java.txt.

    python3 tools/ui_style.py           write the copies
    python3 tools/ui_style.py --check   exit 1 if a copy differs from what would be written (tools/pr_checks.py runs this)

Change the look in the two .txt files, then run this. Only the lines in MODS below differ between mods.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "ui_style"

MODS = [
    {
        "dir": "src/client/java/com/jaymospowers/client",
        "package": "com.jaymospowers.client",
        "cls": "UiStyle",
        "doc": "The look every Jaymo's Powers screen shares (the same one Jaymo's Kingdoms' {@code Ui} and Jaymo's Kitchen's\n"
               " * {@code KitchenUi} draw)",
        "accent": "GOLD",
        "accent_doc": "The accent a Powers screen takes when it has none of its own (most take their power's colour).",
        "extras": "",
    },
    {
        "dir": "kingdoms/src/client/java/com/jaymoskingdoms/client",
        "package": "com.jaymoskingdoms.client",
        "cls": "Ui",
        "doc": "The look every Jaymo's Kingdoms screen shares (the same one Jaymo's Powers' {@code UiStyle} and Jaymo's Kitchen's\n"
               " * {@code KitchenUi} draw)",
        "accent": "GOLD",
        "accent_doc": "The Kingdoms accent: the shared gold (journal, class pick, stables).",
        "extras": "\t/** One accent per skill pillar. */\n"
                  "\tpublic static final int SURVIVAL = 0xFF66C266, STEALTH = 0xFF9A7BE0, STRENGTH = 0xFFE06A4A;\n",
    },
    {
        "dir": "kitchen/src/client/java/com/jaymoskitchen/client",
        "package": "com.jaymoskitchen.client",
        "cls": "KitchenUi",
        "doc": "The look every Jaymo's Kitchen screen shares (the same one Jaymo's Powers' {@code UiStyle} and Jaymo's Kingdoms'\n"
               " * {@code Ui} draw)",
        "accent": "0xFFE0A050",
        "accent_doc": "The Kitchen's accent: a warm, cooked-crust orange.",
        "extras": "\t/** A middling result (between {@link #GOOD} and {@link #BAD}): the shared gold. */\n"
                  "\tpublic static final int OK = GOLD;\n",
    },
]

HEAD = """package {package};

import java.util.ArrayList;
import java.util.List;
import net.minecraft.client.gui.Font;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.network.chat.Component;
import net.minecraft.util.FormattedCharSequence;
import net.minecraft.util.Util;
import net.minecraft.world.inventory.Slot;
import net.minecraft.world.item.ItemStack;
import org.jspecify.annotations.Nullable;

/**
 * {doc}: a dark see-through panel with a coloured stripe along its top, a header (icon, title in the accent, a dim
 * line under it, a rule), striped rows that light up under the mouse, sunken wells for items and slots, flat buttons,
 * and a box at the bottom that shows the hovered row in full. Text never gets cut: a long line slides, a full box scrolls.
 *
 * <p>Generated by {{@code tools/ui_style.py}} from {{@code tools/ui_style/core.java.txt}}, so the three mods' copies stay
 * the same. Change the look there and run the tool; an edit made here is overwritten, and the PR checks fail on it.
 */
public final class {cls} {{
	public static final int PANEL = 0xD0101018, ROW = 0x30FFFFFF, ROW_ALT = 0x18FFFFFF, ROW_HOVER = 0x50FFFFFF, ROW_PICKED = 0x40FFFFFF,
		CHIP = 0xA0000000, TEXT = 0xFFFFFFFF, DIM = 0xFFA8A8B8, HINT = 0xFF707080, BAR_BACK = 0xFF303030, WELL_EDGE = 0xFF34343E,
		WELL = 0xFF0C0C12, BUTTON_RIM_OFF = 0xA0505050;
	/** The pack's one gold, green (good, ready, done) and red (bad, missing, broken), the same on screens and the HUD. */
	public static final int GOLD = 0xFFFFD54A, GOOD = 0xFF66C266, BAD = 0xFFE05050;
	/** {accent_doc} */
	public static final int ACCENT = {accent};
{extras}	/** Height of the header (title, dim line, rule), of one wrapped line in a detail box, and of a flat button. */
	public static final int HEADER = 34, LINE = 9, BUTTON_H = 16;

	private {cls}() {{
	}}

"""


def outputs():
    core = (SRC / "core.java.txt").read_text(encoding="utf-8")
    button = (SRC / "FlatButton.java.txt").read_text(encoding="utf-8")
    out = {}
    for mod in MODS:
        base = ROOT / mod["dir"]
        out[base / (mod["cls"] + ".java")] = HEAD.format(**mod) + core + "}\n"
        out[base / "ui" / "FlatButton.java"] = button.replace("@PACKAGE@", mod["package"]).replace("@STYLE@", mod["cls"])
    return out


def main():
    check = "--check" in sys.argv
    bad = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        if check:
            bad.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(ROOT).as_posix())
    if bad:
        print("The shared screen style is out of step in: " + ", ".join(bad))
        print("Change tools/ui_style/*.txt and run `python3 tools/ui_style.py`; don't edit the copies by hand.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
