"""PostToolUse hook (Write|Edit): warns the agent the moment it edits a file PRs must never change, instead of finding
out at PR time from tools/pr_checks.py. It only warns, never blocks, and never fails (Andy's pick, 2026-11-19, after
the warn-only edit hook in imisic/claude-obsidian-vault).

No-touch files: a mod's `version=` line (gradle.properties, kingdoms/, kitchen/), the MODLOGs and docs/modlog/, and
docs/codemap/. The Release workflow changes all of them after a merge; a PR adds a change note instead
(changes/README.md). On master itself (the Release workflow, or Andy fixing a MODLOG by hand) nothing is said.
"""
import json
import os
import re
import subprocess
import sys

MODLOGS = ("MODLOG.md", "kingdoms/MODLOG.md", "kitchen/MODLOG.md")
PROPERTIES = ("gradle.properties", "kingdoms/gradle.properties", "kitchen/gradle.properties")


def git(repo, *args):
    try:
        return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.SubprocessError):
        return ""


def version(text):
    m = re.search(r"^version\s*=\s*(\S+)", text or "", re.M)
    return m.group(1) if m else None


def problem(repo, rel, tool_input):
    if rel in MODLOGS or rel.startswith("docs/modlog/"):
        return (f"{rel} is a MODLOG: a PR never adds to it. Put the entry's text in a change note, "
                "changes/<powers|kingdoms|kitchen>/<branch-name>.md (see changes/README.md), and undo this edit.")
    if rel.startswith("docs/codemap/"):
        return (f"{rel} is regenerated by the Release workflow after each merge. Don't commit it: "
                "`git checkout origin/master -- docs/codemap` puts it back.")
    if rel in PROPERTIES:
        now = version(open(os.path.join(repo, rel), encoding="utf-8").read()) if os.path.exists(os.path.join(repo, rel)) else None
        master = version(git(repo, "show", f"origin/master:{rel}"))
        if master is None:  # no origin/master here: fall back to the edit itself
            old, new = version(tool_input.get("old_string", "")), version(tool_input.get("new_string", ""))
            changed = new is not None and new != old
        else:
            changed = now is not None and now != master
        if changed:
            return (f"{rel}: the `version=` line changed (master has {master or 'another value'}). PRs never change "
                    "versions: the Release workflow bumps them after the merge. Put the line back and add a change "
                    "note instead (`bump: minor` in the note if Andy asked for a bigger step).")
    return None


def main():
    try:
        event = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        return
    tool_input = event.get("tool_input") or {}
    path = tool_input.get("file_path")
    repo = os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or os.getcwd()
    if not path:
        return
    top = git(repo, "rev-parse", "--show-toplevel").strip() or repo
    try:
        rel = os.path.relpath(os.path.realpath(path), os.path.realpath(top)).replace("\\", "/")
    except ValueError:  # another drive on Windows
        return
    if rel.startswith("../"):
        top = git(os.path.dirname(path), "rev-parse", "--show-toplevel").strip()  # a file in another worktree
        if not top:
            return
        rel = os.path.relpath(os.path.realpath(path), os.path.realpath(top)).replace("\\", "/")
    if git(top, "rev-parse", "--abbrev-ref", "HEAD").strip() == "master":
        return
    message = problem(top, rel, tool_input)
    if message:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse",
                                                 "additionalContext": "No-touch file: " + message}}))


if __name__ == "__main__":
    try:
        main()
    except Exception:
        pass  # a hook must never get in an agent's way
    sys.exit(0)
