package com.jaymospowers.client.ui;

import com.jaymospowers.client.UiStyle;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.client.gui.components.Button;
import net.minecraft.client.gui.components.Tooltip;
import net.minecraft.network.chat.Component;
import org.jspecify.annotations.Nullable;

/**
 * The button on our own screens: flat, drawn by {@link UiStyle#button} (a light plate, a thin rim, brighter under the
 * mouse, dim when it can't be pressed), so it sits on the dark panel the same way with any resource pack. It is a
 * vanilla {@link Button} in every other way (clicks, keyboard focus, narration, tooltips), and is built the same way:
 * {@code FlatButton.builder(label, press).bounds(x, y, w, h).build()}. Vanilla's own buttons stay on vanilla's screens.
 *
 * <p>Generated by {@code tools/ui_style.py} from {@code tools/ui_style/FlatButton.java.txt}; change it there.
 */
public class FlatButton extends Button {
	private int accent;

	protected FlatButton(int x, int y, int w, int h, Component message, OnPress onPress, int accent) {
		super(x, y, w, h, message, onPress, DEFAULT_NARRATION);
		this.accent = accent;
	}

	public static Builder builder(Component message, OnPress onPress) {
		return new Builder(message, onPress);
	}

	/** The rim's colour while the button can be pressed (a screen's own accent). */
	public FlatButton accent(int accent) {
		this.accent = accent;
		return this;
	}

	@Override
	protected void extractContents(GuiGraphicsExtractor graphics, int mouseX, int mouseY, float a) {
		UiStyle.button(graphics, Minecraft.getInstance().font, getX(), getY(), getWidth(), getHeight(), getMessage(), this.accent,
			isHoveredOrFocused(), this.active);
	}

	/** Vanilla's button builder, making a flat button: the same calls, plus {@link #accent}. */
	public static final class Builder extends Button.Builder {
		private final Component message;
		private final OnPress onPress;
		private @Nullable Tooltip tooltip;
		private int x, y, width = DEFAULT_WIDTH, height = UiStyle.BUTTON_H, accent = UiStyle.DIM;

		private Builder(Component message, OnPress onPress) {
			super(message, onPress);
			this.message = message;
			this.onPress = onPress;
		}

		@Override
		public Builder pos(int x, int y) {
			this.x = x;
			this.y = y;
			return this;
		}

		@Override
		public Builder width(int width) {
			this.width = width;
			return this;
		}

		@Override
		public Builder size(int width, int height) {
			this.width = width;
			this.height = height;
			return this;
		}

		@Override
		public Builder bounds(int x, int y, int width, int height) {
			return pos(x, y).size(width, height);
		}

		@Override
		public Builder tooltip(@Nullable Tooltip tooltip) {
			this.tooltip = tooltip;
			return this;
		}

		/** The rim's colour (the default is a neutral light grey that suits any screen). */
		public Builder accent(int accent) {
			this.accent = accent;
			return this;
		}

		@Override
		public FlatButton build() {
			FlatButton button = new FlatButton(this.x, this.y, this.width, this.height, this.message, this.onPress, this.accent);
			button.setTooltip(this.tooltip);
			return button;
		}
	}
}
