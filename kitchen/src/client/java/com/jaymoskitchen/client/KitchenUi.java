/**
 * The look every Jaymo's Kitchen screen shares (the same one Jaymo's Powers' {@code UiStyle} and Jaymo's Kingdoms'
 * {@code Ui} draw): a dark see-through panel with a coloured stripe along its top, a header (icon, title in the accent, a dim
 * line under it, a rule), striped rows that light up under the mouse, sunken wells for items and slots, flat buttons,
 * and a box at the bottom that shows the hovered row in full. Text never gets cut: a long line slides, a full box scrolls.
 *
 * <p>Generated by {@code tools/ui_style.py} from {@code tools/ui_style/core.java.txt}, so the three mods' copies stay
 * the same. Change the look there and run the tool; an edit made here is overwritten, and the PR checks fail on it.
 */
public final class KitchenUi {
	/**
	 * The player's pick between the dark look and vanilla's inventory grey ({@code /screenlook dark|grey}, kept in
	 * {@code config/jaymospowers-screenlook.properties}), read once when the game starts: every colour below has a grey twin.
	 * Text keeps its light colours here; on a grey panel Jaymo's Powers draws it dark ({@link #panel} marks the frame).
	 */
	public static final boolean GREY = grey();
	public static final int PANEL = c(0xD0101018, 0xFFC6C6C6), ROW = c(0x30FFFFFF, 0x18000000), ROW_ALT = c(0x18FFFFFF, 0x0C000000),
		ROW_HOVER = c(0x50FFFFFF, 0x38000000), ROW_PICKED = c(0x40FFFFFF, 0x28000000), CHIP = c(0xA0000000, 0xFF8B8B8B), TEXT = 0xFFFFFFFF,
		DIM = 0xFFA8A8B8, HINT = 0xFF707080, BAR_BACK = c(0xFF303030, 0xFF555555), WELL_EDGE = c(0xFF34343E, 0xFF373737),
		WELL = c(0xFF0C0C12, 0xFF8B8B8B), BUTTON_RIM_OFF = c(0xA0505050, 0xFF8B8B8B), WHEEL_DISC = 0xA0101018;
	/** The H character menu's solid window ({@link #window}, {@link #recess}). */
	public static final int WINDOW_EDGE = c(0xFF0A0A0E, 0xFF000000), WINDOW_LIGHT = c(0xFF4A4A52, 0xFFFFFFFF), WINDOW_SHADE = c(0xFF141418, 0xFF555555),
		WINDOW_BODY = c(0xFF2B2B2F, 0xFFC6C6C6), WINDOW_CANVAS = c(0xFF1E1E22, 0xFF8B8B8B), WINDOW_WELL_LIGHT = c(0xFF3E3E46, 0xFFFFFFFF);
	/** The pack's one gold, green (good, ready, done) and red (bad, missing, broken), the same on screens and the HUD. */
	public static final int GOLD = 0xFFFFD54A, GOOD = 0xFF66C266, BAD = 0xFFE05050;
	/** Books, letters and pages: the paper, its darker edge, the ink and faint ink (a struck line, a margin note). */
	public static final int PAPER = 0xFFD8C8A0, PAPER_EDGE = 0xFF8A7650, INK = 0xFF2A1E10, INK_FAINT = 0xFF7A6247;
	/** The Kitchen's accent: a warm, cooked-crust orange. */
	public static final int ACCENT = 0xFFE0A050;
	/** A middling result (between {@link #GOOD} and {@link #BAD}): the shared gold. */
	public static final int OK = GOLD;
	/** Height of the header (title, dim line, rule), of one wrapped line in a detail box, and of a flat button. */
	public static final int HEADER = 34, LINE = 9, BUTTON_H = 16;
	/** The hover box's look ({@link #tip}): the flat panel with a thin rim, from {@code textures/gui/sprites/tooltip/flat_*.png}. */
	public static final Identifier TIP = Identifier.fromNamespaceAndPath("jaymoskitchen", "flat");
	/** The widest a hover box's text runs before it wraps. */
	public static final int TIP_W = 180;

	private KitchenUi() {
	}

	private static boolean grey() {
		Path file = FabricLoader.getInstance().getConfigDir().resolve("jaymospowers-screenlook.properties");
		if (!Files.exists(file)) {
			return false;
		}
		try (InputStream in = Files.newInputStream(file)) {
			Properties state = new Properties();
			state.load(in);
			return "grey".equals(state.getProperty("look"));
		} catch (java.io.IOException | RuntimeException e) {
			return false;
		}
	}

	private static int c(int dark, int grey) {
		return GREY ? grey : dark;
	}

	/** Shared by the three mods through Fabric Loader's object share: true from a grey panel being drawn to the end of the frame. */
	private static boolean @Nullable [] ink;

	/** Marks this frame as drawn on a grey panel, so text after it is drawn dark and without a shadow (Powers' {@code GreyInk}). */
	private static void inked() {
		if (ink == null) {
			FabricLoader.getInstance().getObjectShare().putIfAbsent("jaymos:grey_ink", new boolean[1]);
			ink = FabricLoader.getInstance().getObjectShare().get("jaymos:grey_ink") instanceof boolean[] shared ? shared : new boolean[1];
		}
		ink[0] = true;
	}

	/** The panel and its stripe. */
	public static void panel(GuiGraphicsExtractor graphics, int x, int y, int w, int h, int accent) {
		panel(graphics, x, y, w, h, accent, PANEL);
	}

	/** The same, with another fill (a lighter one where what's behind should show). */
	public static void panel(GuiGraphicsExtractor graphics, int x, int y, int w, int h, int accent, int fill) {
		if (GREY) {
			// (vanilla's inventory window, with the stripe inside its bevel)
			window(graphics, x, y, w, h);
			graphics.fill(x + 3, y + 3, x + w - 3, y + 5, accent);
			return;
		}
		graphics.fill(x, y, x + w, y + h, fill);
		graphics.fill(x, y, x + w, y + 2, accent);
	}

	/**
	 * The solid window of the H character menu (every tab of it, in whichever mod): opaque and bevelled like vanilla's
	 * inventory, in dark tones, because it sits where the inventory does. Other screens use {@link #panel}.
	 */
	public static void window(GuiGraphicsExtractor graphics, int x, int y, int w, int h) {
		if (GREY) {
			inked();
		}
		graphics.fill(x, y, x + w, y + h, WINDOW_EDGE);
		graphics.fill(x + 1, y + 1, x + w - 1, y + h - 1, WINDOW_SHADE);
		graphics.fill(x + 1, y + 1, x + w - 3, y + h - 3, WINDOW_LIGHT);
		graphics.fill(x + 3, y + 3, x + w - 3, y + h - 3, WINDOW_BODY);
	}

	/** A sunken area of a {@link #window}: shadow on top and left, light on bottom and right. */
	public static void recess(GuiGraphicsExtractor graphics, int x, int y, int w, int h) {
		graphics.fill(x, y, x + w, y + h, WINDOW_WELL_LIGHT);
		graphics.fill(x, y, x + w - 1, y + h - 1, WINDOW_SHADE);
		graphics.fill(x + 1, y + 1, x + w - 1, y + h - 1, WINDOW_CANVAS);
	}

	/**
	 * The header: {@code icon} (if any) top-left, {@code title} beside it in the accent, {@code sub} dim under it, both
	 * cut to {@code textW} (0: the panel's width), and a rule across under them.
	 */
	public static void header(GuiGraphicsExtractor graphics, Font font, int x, int y, int w, @Nullable ItemStack icon, Component title,
		@Nullable Component sub, int accent, int textW) {
		int tx = x + 8;
		if (icon != null && !icon.isEmpty()) {
			graphics.item(icon, x + 8, y + 8);
			tx = x + 28;
		}
		int room = textW > 0 ? textW : x + w - 8 - tx;
		line(graphics, font, title, tx, y + 7, room, accent);
		if (sub != null) {
			line(graphics, font, sub, tx, y + 18, room, DIM);
		}
		rule(graphics, x + 6, x + w - 6, y + HEADER - 4);
	}

	/** A thin rule across, between a header and the rows or the rows and the detail box. */
	public static void rule(GuiGraphicsExtractor graphics, int x0, int x1, int y) {
		graphics.fill(x0, y, x1, y + 1, ROW);
	}

	/** One striped row: lighter every other one, lighter still under the mouse. */
	public static void row(GuiGraphicsExtractor graphics, int x0, int y0, int x1, int y1, int index, boolean hover) {
		graphics.fill(x0, y0, x1, y1, hover ? ROW_HOVER : index % 2 == 0 ? ROW : ROW_ALT);
	}

	/** A sunken box an item or a slot sits in. */
	public static void well(GuiGraphicsExtractor graphics, int x, int y, int w, int h) {
		graphics.fill(x, y, x + w, y + h, WELL_EDGE);
		graphics.fill(x + 1, y + 1, x + w - 1, y + h - 1, WELL);
	}

	/** An item in an 18x18 well whose inside starts at (x, y), with its count. */
	public static void itemWell(GuiGraphicsExtractor graphics, Font font, ItemStack stack, int x, int y) {
		well(graphics, x - 1, y - 1, 18, 18);
		graphics.item(stack, x, y);
		graphics.itemDecorations(font, stack, x, y, null);
	}

	/** A bigger 26x26 well for something made (an output, a finished dish), the item centred in it. */
	public static void outputWell(GuiGraphicsExtractor graphics, Font font, ItemStack stack, int x, int y) {
		well(graphics, x - 5, y - 5, 26, 26);
		graphics.item(stack, x, y);
		graphics.itemDecorations(font, stack, x, y, null);
	}

	/** A well behind every slot of a container screen that's showing. */
	public static void slots(GuiGraphicsExtractor graphics, List<Slot> slots, int left, int top) {
		for (Slot slot : slots) {
			if (slot.isActive()) {
				well(graphics, left + slot.x - 1, top + slot.y - 1, 18, 18);
			}
		}
	}

	/**
	 * The flat button every screen shares ({@code FlatButton} is the widget): a light plate with a 1 px rim in the
	 * accent, brighter under the mouse; dim with a grey rim when it can't be pressed. Its label is centred and slides
	 * if it is too long.
	 */
	public static void button(GuiGraphicsExtractor graphics, Font font, int x, int y, int w, int h, Component label, int accent, boolean hover,
		boolean active) {
		graphics.fill(x, y, x + w, y + h, !active ? ROW_ALT : hover ? ROW_HOVER : ROW);
		int rim = !active ? BUTTON_RIM_OFF : hover ? TEXT : accent;
		graphics.fill(x, y, x + w, y + 1, rim);
		graphics.fill(x, y + h - 1, x + w, y + h, rim);
		graphics.fill(x, y + 1, x + 1, y + h - 1, rim);
		graphics.fill(x + w - 1, y + 1, x + w, y + h - 1, rim);
		lineCentred(graphics, font, label, x + w / 2, y + (h - 8) / 2, w - 6, active ? TEXT : HINT);
	}

	/**
	 * The wheel every hold-a-key menu shares (the symbiote's look): a dark disc behind the tiles and a thin ring just
	 * inside them. {@code radius} is from the centre to the tiles' centres, {@code tile} a tile's size.
	 */
	public static void wheel(GuiGraphicsExtractor graphics, int cx, int cy, int radius, int tile) {
		int outer = radius + tile / 2 + 6, inner = wheelInner(radius, tile);
		for (int y = -outer; y <= outer; y++) {
			int half = (int)Math.sqrt(outer * outer - y * y);
			graphics.fill(cx - half, cy + y, cx + half, cy + y + 1, WHEEL_DISC);
		}
		for (int k = 0; k < 120; k++) {
			double t = k * Math.PI * 2.0 / 120.0;
			int x = cx + (int)Math.round(Math.cos(t) * inner), y = cy + (int)Math.round(Math.sin(t) * inner);
			graphics.fill(x, y, x + 1, y + 1, 0x30FFFFFF);
		}
	}

	/** The radius of a {@link #wheel}'s thin ring: the room its middle has for a name, a bar or toggle chips. */
	public static int wheelInner(int radius, int tile) {
		return radius - tile / 2 - 6;
	}

	/** A wheel's pointer: dots in the accent from the ring toward the picked tile, along {@code angle} (radians). */
	public static void wheelPointer(GuiGraphicsExtractor graphics, int cx, int cy, int radius, int tile, double angle, int accent) {
		for (int r = wheelInner(radius, tile) + 4; r < radius - tile / 2 - 2; r += 4) {
			int x = cx + (int)Math.round(Math.cos(angle) * r), y = cy + (int)Math.round(Math.sin(angle) * r);
			graphics.fill(x, y, x + 2, y + 2, accent);
		}
	}

	/** One tile of a wheel (or a toggle chip in its middle): a dark plate, lighter when picked, with a 1 px rim. */
	public static void wheelTile(GuiGraphicsExtractor graphics, int x, int y, int size, int index, boolean picked, int rim) {
		graphics.fill(x, y, x + size, y + size, 0xA0000000);
		graphics.fill(x, y, x + size, y + size, picked ? 0x50FFFFFF : index % 2 == 0 ? 0x30FFFFFF : 0x18FFFFFF);
		graphics.fill(x, y, x + size, y + 1, rim);
		graphics.fill(x, y + size - 1, x + size, y + size, rim);
		graphics.fill(x, y + 1, x + 1, y + size - 1, rim);
		graphics.fill(x + size - 1, y + 1, x + size, y + size - 1, rim);
	}

	/** A thin bar, {@code share} of it filled. */
	public static void bar(GuiGraphicsExtractor graphics, int x, int y, int w, int h, float share, int color) {
		graphics.fill(x, y, x + w, y + h, BAR_BACK);
		graphics.fill(x, y, x + Math.round(w * Math.max(0.0F, Math.min(1.0F, share))), y + h, color);
	}

	/** (UI text pass) How a line too long for its room slides (a pause each end, ms per pixel), and how a detail box too full scrolls (ms per line). */
	public static final long SLIDE_PAUSE_MS = 1500L, SLIDE_MS_PER_PX = 35L, SCROLL_PAUSE_MS = 3000L, SCROLL_MS_PER_LINE = 1100L;

	/** One line of text. If it would run past {@code width} it slides slowly back and forth inside it, so all of it shows. */
	public static void line(GuiGraphicsExtractor graphics, Font font, Component text, int x, int y, int width, int color) {
		String s = text.getString();
		int over = font.width(s) - width;
		if (over <= 0) {
			graphics.text(font, s, x, y, color);
			return;
		}
		graphics.enableScissor(x, y - 1, x + Math.max(0, width), y + LINE + 1);
		graphics.text(font, s, x - slide(over, SLIDE_MS_PER_PX, SLIDE_PAUSE_MS), y, color);
		graphics.disableScissor();
	}

	/** The same, right-aligned to {@code right} (sliding inside {@code width} left of it when too long). */
	public static void lineRight(GuiGraphicsExtractor graphics, Font font, Component text, int right, int y, int width, int color) {
		int textW = font.width(text.getString());
		if (textW <= width) {
			graphics.text(font, text.getString(), right - textW, y, color);
		} else {
			line(graphics, font, text, right - width, y, width, color);
		}
	}

	/** The same, centred on {@code centre} (sliding inside {@code width} round it when too long). */
	public static void lineCentred(GuiGraphicsExtractor graphics, Font font, Component text, int centre, int y, int width, int color) {
		int textW = font.width(text.getString());
		if (textW <= width) {
			graphics.text(font, text.getString(), centre - textW / 2, y, color);
		} else {
			line(graphics, font, text, centre - width / 2, y, width, color);
		}
	}

	/** Where a slide of {@code over} steps is now (0 to {@code over}): a pause, along at {@code msPerStep}, a pause, and back. */
	public static int slide(int over, long msPerStep, long pause) {
		long run = over * msPerStep, t = Util.getMillis() % (2 * (pause + run));
		if (t < pause) {
			return 0;
		}
		t -= pause;
		if (t < run) {
			return (int)(t / msPerStep);
		}
		t -= run;
		return t < pause ? over : over - (int)Math.min(over, (t - pause) / msPerStep);
	}

	/** {@code s} cut to {@code width} with "..." (for HUD bits with no room to slide; screens use {@link #line}). */
	public static String cut(Font font, String s, int width) {
		if (font.width(s) <= width) {
			return s;
		}
		return font.plainSubstrByWidth(s, Math.max(0, width - font.width("..."))) + "...";
	}

	/**
	 * The detail box: a rule, then {@code name} in {@code color} (if any) and {@code text} wrapped under it, in
	 * {@code lines} lines. With no name, the text is dim (a hint, or the screen's lead). Text that needs more lines
	 * scrolls slowly up through the box and back (a thin bar at the side shows where), so none of it is cut off.
	 */
	public static void detail(GuiGraphicsExtractor graphics, Font font, int x, int y, int w, int lines, @Nullable Component name, int color,
		List<Component> text) {
		rule(graphics, x + 6, x + w - 6, y);
		int ty = y + 5, room = lines;
		boolean named = name != null && !name.getString().isEmpty();
		if (named) {
			line(graphics, font, name, x + 9, ty, w - 18, color);
			ty += 10;
			room--;
		}
		if (room <= 0) {
			return;
		}
		List<FormattedCharSequence> rows = new ArrayList<>();
		List<Integer> colors = new ArrayList<>();
		for (Component part : text) {
			int partColor = part.getStyle().getColor() != null ? 0xFF000000 | part.getStyle().getColor().getValue() : named ? TEXT : DIM;
			for (FormattedCharSequence seq : font.split(part, w - 18)) {
				rows.add(seq);
				colors.add(partColor);
			}
		}
		int view = room * LINE, over = Math.max(0, rows.size() - room) * LINE;
		int shift = over > 0 ? slide(over, SCROLL_MS_PER_LINE / LINE, SCROLL_PAUSE_MS) : 0;
		if (over > 0) {
			graphics.enableScissor(x, ty - 1, x + w, ty + view);
		}
		for (int i = 0; i < rows.size(); i++) {
			int ly = ty + i * LINE - shift;
			if (ly > ty - LINE && ly < ty + view) {
				graphics.text(font, rows.get(i), x + 9, ly, colors.get(i));
			}
		}
		if (over > 0) {
			graphics.disableScissor();
			scrollbar(graphics, x + w - 6, ty, view - 1, view, view + over, shift);
		}
	}

	/**
	 * The hover box for something that has no room for a detail box (a swatch, a tab, a gauge): vanilla's tooltip, so it
	 * sits above everything and stays on the screen, in the flat panel look. Item slots keep the item's own tooltip.
	 */
	public static void tip(GuiGraphicsExtractor graphics, Font font, Component text, int mouseX, int mouseY) {
		graphics.setTooltipForNextFrame(font, font.split(text, TIP_W), mouseX, mouseY, TIP);
	}

	/** The same for several lines (each wraps on its own). */
	public static void tip(GuiGraphicsExtractor graphics, Font font, List<Component> lines, int mouseX, int mouseY) {
		List<FormattedCharSequence> rows = new ArrayList<>();
		for (Component line : lines) {
			rows.addAll(font.split(line, TIP_W));
		}
		graphics.setTooltipForNextFrame(font, rows, mouseX, mouseY, TIP);
	}

	/** A button's or widget's hover text in the same look ({@code widget.setTooltip(tipOf(text))}). */
	public static Tooltip tipOf(Component text) {
		return Tooltip.create(text, Optional.empty(), TIP);
	}

	/** How many lines {@link #detail} needs for these, at this width. */
	public static int detailLines(Font font, int w, @Nullable Component name, List<Component> text) {
		int n = name != null && !name.getString().isEmpty() ? 1 : 0;
		for (Component part : text) {
			n += font.split(part, w - 18).size();
		}
		return n;
	}

	/** The height a detail box of {@code lines} lines takes. */
	public static int detailHeight(int lines) {
		return 5 + lines * LINE + 4;
	}

	/**
	 * {@code text} wrapped to {@code width} in {@code lines} lines {@code lineH} apart; more than fits scrolls slowly up
	 * through them and back (a thin bar just right of {@code width} shows where), so none is cut off. Returns the lines used.
	 */
	public static int wrapped(GuiGraphicsExtractor graphics, Font font, Component text, int x, int y, int width, int lines, int lineH, int color,
		boolean shadow) {
		List<FormattedCharSequence> split = font.split(text, width);
		int n = Math.min(lines, split.size());
		if (n <= 0) {
			return 0;
		}
		int view = n * lineH, over = (split.size() - n) * lineH;
		int shift = over > 0 ? slide(over, SCROLL_MS_PER_LINE / lineH, SCROLL_PAUSE_MS) : 0;
		if (over > 0) {
			graphics.enableScissor(x - 1, y - 1, x + width + 4, y + view);
		}
		for (int i = 0; i < split.size(); i++) {
			int ly = y + i * lineH - shift;
			if (ly > y - lineH && ly < y + view) {
				graphics.text(font, split.get(i), x, ly, color, shadow);
			}
		}
		if (over > 0) {
			graphics.disableScissor();
			scrollbar(graphics, x + width + 2, y, view - 1, view, view + over, shift);
		}
		return n;
	}

	/** A thin scrollbar at {@code x}, from {@code top} down {@code track}. */
	public static void scrollbar(GuiGraphicsExtractor graphics, int x, int top, int track, int view, int content, int scroll) {
		if (content <= view) {
			return;
		}
		int thumb = Math.max(8, track * view / content);
		int at = top + (track - thumb) * scroll / Math.max(1, content - view);
		graphics.fill(x, top, x + 2, top + track, c(0x40FFFFFF, 0x40000000));
		graphics.fill(x, at, x + 2, at + thumb, c(0xC0FFFFFF, 0xC0000000));
	}

	public static boolean over(int mouseX, int mouseY, int x, int y, int w, int h) {
		return mouseX >= x && mouseX < x + w && mouseY >= y && mouseY < y + h;
	}
}
