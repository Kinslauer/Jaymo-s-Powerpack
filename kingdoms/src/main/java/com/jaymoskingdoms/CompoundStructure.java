package com.jaymoskingdoms;

import com.mojang.datafixers.util.Either;
import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderSet;
import net.minecraft.core.registries.Registries;
import net.minecraft.core.registries.codec.RegistryCodecs;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.levelgen.WorldgenRandom;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructurePiece;
import net.minecraft.world.level.levelgen.structure.StructureType;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePiecesBuilder;

/**
 * A compound: several other structures generated together as one ({@code jaymoskingdoms:compound}). Where one would
 * stand, {@code min_count} to {@code max_count} of its {@code members} go up in a ring round an open middle (room for
 * a kingdom's builders), each assembled exactly as it would be on its own (its own jigsaw, its own biome rule, its own
 * height on the land), so a member only goes where it could have generated by itself. Members that would overlap one
 * another, or reach past what a structure may span ({@link #REACH}), are pushed further out or swapped for another.
 * Used for ATi Structures' compounds ({@link AtiCompounds}); nothing about it is ATi's own.
 */
public final class CompoundStructure extends Structure {
	/** Members in a compound, by default (the data may set its own). */
	static final int MIN_MEMBERS = 3, MAX_MEMBERS = 4;
	/** How far (chunks) each member's start is from the compound's middle, by default; how much further a crowded one may be pushed. */
	static final int RING_CHUNKS = 3, PUSH_CHUNKS = 2;
	/** Members tried at each spot before it's pushed further out; how far (degrees) a spot may stray from even spacing. */
	static final int TRIES_PER_SPOT = 6, ANGLE_JITTER = 25;
	/** Blocks kept clear between two members. */
	static final int GAP = 6;
	/** The furthest a piece may reach from the compound's own chunk (the game only looks 8 chunks round for structures). */
	static final int REACH = 128;

	public static final MapCodec<CompoundStructure> CODEC = RecordCodecBuilder.<CompoundStructure>mapCodec(i -> i.group(
			settingsCodec(i),
			RegistryCodecs.holderSet(Registries.STRUCTURE).fieldOf("members").forGetter(c -> c.members),
			Codec.intRange(1, 8).optionalFieldOf("min_count", MIN_MEMBERS).forGetter(c -> c.minCount),
			Codec.intRange(1, 8).optionalFieldOf("max_count", MAX_MEMBERS).forGetter(c -> c.maxCount),
			Codec.intRange(1, 6).optionalFieldOf("ring", RING_CHUNKS).forGetter(c -> c.ring))
		.apply(i, CompoundStructure::new));

	public static StructureType<CompoundStructure> TYPE;

	private final HolderSet<Structure> members;
	private final int minCount, maxCount, ring;

	public CompoundStructure(StructureSettings settings, HolderSet<Structure> members, int minCount, int maxCount, int ring) {
		super(settings);
		this.members = members;
		this.minCount = Math.min(minCount, maxCount);
		this.maxCount = Math.max(minCount, maxCount);
		this.ring = ring;
	}

	@Override
	protected Optional<GenerationStub> findGenerationPoint(GenerationContext context) {
		WorldgenRandom random = context.random();
		List<Holder<Structure>> choices = new ArrayList<>();
		for (Holder<Structure> h : this.members) {
			// (never a compound inside a compound)
			if (h.isBound() && !(h.value() instanceof CompoundStructure)) {
				choices.add(h);
			}
		}
		if (choices.isEmpty()) {
			return Optional.empty();
		}
		int want = this.minCount + random.nextInt(this.maxCount - this.minCount + 1);
		ChunkPos middle = context.chunkPos();
		int x0 = middle.getMinBlockX() - REACH, z0 = middle.getMinBlockZ() - REACH;
		int x1 = middle.getMaxBlockX() + REACH, z1 = middle.getMaxBlockZ() + REACH;
		StructurePiecesBuilder all = new StructurePiecesBuilder();
		List<BoundingBox> placed = new ArrayList<>();
		List<Holder<Structure>> unused = new ArrayList<>(choices);
		BlockPos first = null;
		double turn = random.nextDouble() * Math.PI * 2.0;
		for (int k = 0; k < want; k++) {
			double angle = turn + k * Math.PI * 2.0 / want + Math.toRadians(random.nextInt(2 * ANGLE_JITTER + 1) - ANGLE_JITTER);
			boolean done = false;
			for (int push = 0; push <= PUSH_CHUNKS && !done; push++) {
				int dist = this.ring + push;
				ChunkPos spot = new ChunkPos(middle.x() + (int)Math.round(Math.cos(angle) * dist), middle.z() + (int)Math.round(Math.sin(angle) * dist));
				for (int t = 0; t < TRIES_PER_SPOT && !done; t++) {
					// a fresh one while any are left, so a compound is a mix
					List<Holder<Structure>> from = unused.isEmpty() ? choices : unused;
					Holder<Structure> pick = from.get(random.nextInt(from.size()));
					Structure member = pick.value();
					GenerationContext there = new GenerationContext(context.registryAccess(), context.chunkGenerator(), context.biomeSource(),
						context.climateSampler(), context.randomState(), context.structureTemplateManager(), context.seed(), spot,
						context.heightAccessor(), member.biomes()::contains);
					Optional<GenerationStub> stub = member.findValidGenerationPoint(there);
					if (stub.isEmpty()) {
						continue;
					}
					StructurePiecesBuilder pieces = stub.get().getPiecesBuilder();
					if (pieces.isEmpty()) {
						continue;
					}
					BoundingBox box = pieces.getBoundingBox();
					if (box.minX() < x0 || box.maxX() > x1 || box.minZ() < z0 || box.maxZ() > z1 || crowded(box, placed)) {
						continue;
					}
					for (StructurePiece piece : pieces.build().pieces()) {
						all.addPiece(piece);
					}
					placed.add(box);
					unused.remove(pick);
					if (first == null) {
						first = stub.get().position();
					}
					done = true;
				}
			}
		}
		if (first == null) {
			return Optional.empty();
		}
		return Optional.of(new GenerationStub(first, Either.right(all)));
	}

	/** It comes within {@link #GAP} of a member already placed. */
	private static boolean crowded(BoundingBox box, List<BoundingBox> placed) {
		BoundingBox wide = box.inflatedBy(GAP, 0, GAP);
		for (BoundingBox other : placed) {
			if (wide.intersects(other.minX(), other.minZ(), other.maxX(), other.maxZ())) {
				return true;
			}
		}
		return false;
	}

	@Override
	public StructureType<?> type() {
		return TYPE;
	}
}
